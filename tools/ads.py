"""Google Ads tag + conversion helper: the ONE place the site's Ads tracking is defined.

Every builder puts ads.TAG in <head> (build_blog.head → blog, resources, tools, services, shop, cleanup, LLC;
build_landing; build_newsletter web issues). write_assets() writes site/assets/ads.js and refreshes the tag
between <!--ads:tag--> markers in the hand-built pages (site/index.html, site/404.html).

site/assets/ads.js (loaded once per page):
  - loads gtag config for AW-18505873837 (no extra cookies beyond Google's own gtag);
  - one delegated click listener: a[href^="tel:"] (or data-conv="call") → "Click to call" conversion;
    Google booking-calendar links (calendar.google.com/calendar/appointments) or data-conv="book"
    → "Opened booking calendar" (secondary / observe-only in Google Ads);
  - window.mfaLead(form, params) → "Submit lead form" conversion. Call it ONLY after the /llc-formation/
    form is confirmed sent (it keeps its own thanks flow).
  - window.mfaContactThanks() → "Contact form submitted" conversion, called on load of /contact/thanks/ only.
    The general contact/quote forms (home contact, landing pages, /bookkeeping-cleanup/) do NOT call mfaLead:
    after FormSubmit confirms the send they run contact_redirect(form) (sets a sessionStorage flag, goes to
    /contact/thanks/). The thanks page fires once per send: the flag is consumed on first load, so a reload or a
    direct visit fires nothing. One send never fires both labels (Zain's yes to lead tracking, 2026-10-25).
    Newsletter signups and blog questions are not leads and must not call either.
Labels come from Google Ads → Goals → Conversions → (action) → Tag setup.
"""
import hashlib
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent / "site"

ADS = {
    "id": "AW-18505873837",          # Google Ads account 402-577-1790
    "call": "_Z6FCLjJk5sdEK3zpPhE",  # "ContactClick to call"
    "form": "rNQJCK2_kJsdEK3zpPhE",  # "Submit lead form"
    "book": "OUTYCLC_kJsdEK3zpPhE",  # "Opened booking calendar" (secondary)
    "contact": "Slt4CJy29qgdEK3zpPhE",  # "Contact form submitted" (fired on /contact/thanks/ only)
    "purchase": "L0plCOPA2aodEK3zpPhE",  # "Purchase" (Stripe thank-you pages; created 2026-10-26, Zain's yes)
}
THANKS = "/contact/thanks/"
THANKS_ABS = "https://mfa-advisory.com" + THANKS   # FormSubmit _next (used if a form ever posts without JS)
SENT_KEY = "mfa_contact_sent"

JS = """/* MFA Google Ads tag helper. Generated by tools/ads.py; do not edit by hand. */
(function(w,d){
if(w.mfaLead)return;
var A={id:'%(id)s',call:'%(call)s',form:'%(form)s',book:'%(book)s',contact:'%(contact)s',purchase:'%(purchase)s'};
w.dataLayer=w.dataLayer||[];
if(typeof w.gtag!=='function')w.gtag=function(){w.dataLayer.push(arguments);};
w.gtag('js',new Date());w.gtag('config',A.id);
var X=(function(){try{var q=w.location.search;if(/[?&]internal=1/.test(q))w.localStorage.setItem('mfa_internal','1');if(/[?&]internal=0/.test(q))w.localStorage.removeItem('mfa_internal');return !!w.navigator.webdriver||!/(^|\\.)mfa-advisory\\.com$/.test(w.location.hostname)||w.localStorage.getItem('mfa_internal')==='1';}catch(e){return !!w.navigator.webdriver;}})();
function conv(k){if(X||!A[k])return;w.gtag('event','conversion',{send_to:A.id+'/'+A[k]});}
w.mfaLead=function(form,params){conv('form');if(X)return;var p={form:form||'lead'};for(var k in params||{})p[k]=params[k];w.gtag('event','generate_lead',p);};
w.mfaContactThanks=function(){var f=null;try{var s=w.sessionStorage;f=s.getItem('%(sent)s');if(f)s.removeItem('%(sent)s');}catch(e){}
if(!f)return false;conv('contact');if(!X)w.gtag('event','generate_lead',{form:f});return true;};
w.mfaPurchase=function(id,v){if(X||!A.purchase)return;w.gtag('event','conversion',{send_to:A.id+'/'+A.purchase,value:Number(v)||1,currency:'USD',transaction_id:String(id||'')});};
d.addEventListener('click',function(e){
var a=e.target&&e.target.closest?e.target.closest('a[href],[data-conv]'):null;if(!a)return;
var k=a.getAttribute('data-conv'),h=a.getAttribute('href')||'';
if(!k){if(/^tel:/i.test(h))k='call';else if(/^https:\\/\\/calendar\\.google\\.com\\/calendar\\/appointments/i.test(h))k='book';}
if(k==='call'||k==='book')conv(k);
},true);
})(window,document);
""" % dict(ADS, sent=SENT_KEY)

VER = hashlib.sha1(JS.encode()).hexdigest()[:10]
# Site-wide verification meta tags ride along with the Ads tag so every page's <head> gets them.
# Pinterest website claim (account pinterest.com/merchant4104, Zain's yes 2026-10-23).
VERIFY = '<meta name="p:domain_verify" content="b4398f09fdd0e385c266cc687acecf36"/>'
TAG = (VERIFY + f'<script async src="https://www.googletagmanager.com/gtag/js?id={ADS["id"]}"></script>'
       f'<script src="/assets/ads.js?v={VER}"></script>')
MARKED = f"<!--ads:tag-->{TAG}<!--/ads:tag-->"
HAND_BUILT = ["index.html", "404.html"]


def contact_redirect(form):
    """JS run after FormSubmit confirms a general contact/quote form: flag the send, then open the thanks page.
    Inline (not in ads.js) so the redirect still works when a blocker stops ads.js."""
    return ("try{sessionStorage.setItem('%s','%s');}catch(e){}location.href='%s';" % (SENT_KEY, form, THANKS))


def next_field():
    """FormSubmit _next hidden field for the general contact/quote forms."""
    return '<input type="hidden" name="_next" value="%s"/>' % THANKS_ABS


def write_assets():
    """Write site/assets/ads.js and refresh the marked tag in the hand-built pages."""
    out = SITE / "assets" / "ads.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != JS:
        out.write_text(JS, encoding="utf-8")
    for name in HAND_BUILT:
        p = SITE / name
        if not p.exists():
            continue
        s = p.read_text(encoding="utf-8")
        if "<!--ads:tag-->" in s:
            new = re.sub(r"<!--ads:tag-->.*?<!--/ads:tag-->", lambda m: MARKED, s, count=1, flags=re.S)
        else:
            new = s.replace("</head>", MARKED + "\n</head>", 1)
        if new != s:
            p.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    write_assets()
    print("wrote site/assets/ads.js", VER)
