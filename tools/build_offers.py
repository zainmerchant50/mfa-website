def src_of(*figs):
    seen, out = set(), []
    for t, u in figs:
        if u not in seen:
            seen.add(u)
            out.append((t, u))
    return out


def cal(form):
    c = json.loads((DATA / "tax-calendar-2027.json").read_text())
    for ent in c["entities"].values():
        for e in (ent if isinstance(ent, list) else ent.get("dates", [])):
            if e.get("form") == form:
                return e
    raise KeyError(form)


